#!/usr/bin/env python3
"""
craft_journey.py — Autonomous E2E Journey & Accessibility Synthesizer
Generates headless Playwright tests, multi-step user journeys, and WCAG AA/AAA visual contrast checks.
"""

import os
import sys
import json
import re
import argparse
from pathlib import Path

def detect_routes_from_filesystem(root_dir="."):
    """Scans directories for frontend routes (Next.js, Vite, Remix, Laravel, etc.)."""
    routes = set()
    root = Path(root_dir)

    # 1. Next.js App Router (app/**/page.{tsx,jsx,js,ts})
    app_dir = root / "src" / "app" if (root / "src" / "app").exists() else root / "app"
    if app_dir.exists():
        for p in app_dir.rglob("page.*"):
            rel = p.relative_to(app_dir).parent.as_posix()
            route = "/" if rel == "." else f"/{rel}"
            # Remove route groups like (auth)
            route = re.sub(r'/\([^)]+\)', '', route)
            # Normalize double slashes
            route = re.sub(r'/+', '/', route)
            routes.add(route or "/")

    # 2. Next.js Pages Router (pages/**/*.{tsx,jsx,js,ts})
    pages_dir = root / "src" / "pages" if (root / "src" / "pages").exists() else root / "pages"
    if pages_dir.exists():
        for p in pages_dir.rglob("*.*"):
            if p.suffix in {".tsx", ".jsx", ".js", ".ts"} and not p.name.startswith(("_", ".")):
                rel = p.relative_to(pages_dir).with_suffix("").as_posix()
                if rel == "index":
                    routes.add("/")
                else:
                    routes.add(f"/{rel.replace('/index', '')}")

    # 3. Laravel web.php / api.php routes
    routes_dir = root / "routes"
    if routes_dir.exists():
        for rf in routes_dir.glob("*.php"):
            try:
                content = rf.read_text(encoding="utf-8", errors="ignore")
                matches = re.findall(r"Route::(get|post|put|delete|match)\s*\(\s*['\"]([^'\"]+)['\"]", content)
                for method, path in matches:
                    routes.add(f"/{path.lstrip('/')}")
            except Exception:
                pass

    # 4. FastAPI / Flask / Express route detections
    for ext in ("*.py", "*.ts", "*.js"):
        for source_file in root.rglob(ext):
            # Skip node_modules, .git, venv
            if any(part in source_file.parts for part in ("node_modules", ".git", "venv", ".venv", "dist", "build")):
                continue
            try:
                content = source_file.read_text(encoding="utf-8", errors="ignore")
                # Express: app.get('/path', ...)
                express_matches = re.findall(r"app\.(get|post|use)\s*\(\s*['\"](/[^'\"]*)['\"]", content)
                for _, path in express_matches:
                    routes.add(path)
                # FastAPI: @app.get("/path") or @router.get("/path")
                fastapi_matches = re.findall(r"@(?:app|router)\.(get|post|put|delete)\s*\(\s*['\"](/[^'\"]*)['\"]", content)
                for _, path in fastapi_matches:
                    routes.add(path)
            except Exception:
                pass

    sorted_routes = sorted(list(routes))
    return sorted_routes if sorted_routes else ["/", "/login", "/dashboard"]

def generate_playwright_ts(routes, base_url="http://localhost:3000", check_contrast=True, test_name="User Journey & Accessibility"):
    """Generates Playwright TypeScript test suite."""
    ts_code = [
        'import { test, expect } from "@playwright/test";',
        '',
        '/**',
        f' * Auto-generated by journey-craft engine.',
        f' * Target: {base_url}',
        f' * Scanned Routes: {len(routes)} routes',
        ' */',
        '',
        f'test.describe("{test_name}", () => {{',
        f'  const BASE_URL = process.env.BASE_URL || "{base_url}";',
        ''
    ]

    # Individual page route sanity & contrast checks
    for route in routes:
        safe_name = route.strip("/").replace("/", "_").replace("-", "_") or "home"
        ts_code.extend([
            f'  test("route: {route} loads and passes visual hygiene", async ({{ page }}) => {{',
            f'    const response = await page.goto(`${{BASE_URL}}{route}`, {{ waitUntil: "domcontentloaded" }});',
            '    expect(response?.status()).toBeLessThan(400);',
            '    await expect(page).not.toHaveTitle(/404|Not Found|Error/i);',
            ''
        ])

        if check_contrast:
            ts_code.extend([
                '    // Verify no invisible or low-contrast text artifacts',
                '    const contrastErrors = await page.evaluate(() => {',
                '      const issues: string[] = [];',
                '      const elements = document.querySelectorAll("h1, h2, h3, p, a, button, span");',
                '      for (const el of Array.from(elements)) {',
                '        const style = window.getComputedStyle(el);',
                '        if (style.display === "none" || style.visibility === "hidden" || style.opacity === "0") continue;',
                '        if (style.color === style.backgroundColor && style.backgroundColor !== "rgba(0, 0, 0, 0)") {',
                '          issues.push(`Hidden text collision on <${el.tagName.toLowerCase()}> with text "${el.textContent?.slice(0, 20)}"`);',
                '        }',
                '      }',
                '      return issues;',
                '    });',
                '    expect(contrastErrors).toHaveLength(0);',
                ''
            ])

        ts_code.extend([
            f'    // Screenshot checkpoint',
            f'    await page.screenshot({{ path: `test-results/screenshots/{safe_name}.png`, fullPage: false }});',
            '  });',
            ''
        ])

    # End-to-end multi-step interactive journey
    ts_code.extend([
        '  test("full multi-step interactive flow", async ({ page }) => {',
        '    // 1. Visit Home / Root',
        '    await page.goto(BASE_URL);',
        '    await expect(page.locator("body")).toBeVisible();',
        '',
        '    // 2. Interactive Navigation Check',
        '    const primaryLinks = page.locator("nav a, header a");',
        '    const linkCount = await primaryLinks.count();',
        '    if (linkCount > 0) {',
        '      const firstLink = primaryLinks.first();',
        '      const href = await firstLink.getAttribute("href");',
        '      if (href && !href.startsWith("http") && !href.startsWith("#")) {',
        '        await firstLink.click();',
        '        await page.waitForLoadState("domcontentloaded");',
        '        expect(page.url()).toContain(href);',
        '      }',
        '    }',
        '',
        '    // 3. Form input and button click resistance test',
        '    const inputs = page.locator("input:not([type=hidden])");',
        '    const inputCount = await inputs.count();',
        '    for (let i = 0; i < Math.min(inputCount, 3); i++) {',
        '      const input = inputs.nth(i);',
        '      if (await input.isVisible() && await input.isEditable()) {',
        '        await input.fill("test_automated_input");',
        '      }',
        '    }',
        '  });',
        '});',
        ''
    ])

    return "\n".join(ts_code)

def generate_playwright_py(routes, base_url="http://localhost:3000", check_contrast=True, test_name="User Journey"):
    """Generates Playwright Python test suite."""
    py_code = [
        'import os',
        'import pytest',
        'from playwright.sync_api import Page, expect',
        '',
        f'BASE_URL = os.environ.get("BASE_URL", "{base_url}")',
        '',
        f'# Auto-generated by journey-craft engine for {test_name}',
        f'# Target Routes: {len(routes)}',
        ''
    ]

    for route in routes:
        safe_name = route.strip("/").replace("/", "_").replace("-", "_") or "home"
        py_code.extend([
            f'def test_route_{safe_name}(page: Page):',
            f'    resp = page.goto(f"{{BASE_URL}}{route}", wait_until="domcontentloaded")',
            f'    assert resp and resp.status < 400',
            f'    expect(page.locator("body")).to_be_visible()',
            f'    os.makedirs("test-results/screenshots", exist_ok=True)',
            f'    page.screenshot(path="test-results/screenshots/{safe_name}.png")',
            ''
        ])

    return "\n".join(py_code)

def main():
    parser = argparse.ArgumentParser(description="Autonomous E2E Journey & Accessibility Synthesizer")
    parser.add_argument("--dir", default=".", help="Root directory to scan for routes")
    parser.add_argument("--routes", nargs="*", help="Explicit routes (e.g. / /login /dashboard)")
    parser.add_argument("--base-url", default="http://localhost:3000", help="Base URL of local or staging app")
    parser.add_argument("--lang", choices=["ts", "py"], default="ts", help="Output test language (ts or py)")
    parser.add_argument("--out-dir", default="tests/e2e", help="Output directory for generated tests")
    parser.add_argument("--no-contrast", action="store_true", help="Disable WCAG contrast audit injections")
    parser.add_argument("--dry-run", action="store_true", help="Print generated test code to stdout without writing")

    args = parser.parse_args()

    # Determine routes
    if args.routes:
        routes = args.routes
    else:
        routes = detect_routes_from_filesystem(args.dir)

    print(f"[journey-craft] Detected / Configured Routes ({len(routes)}):")
    for r in routes:
        print(f"  -> {r}")

    # Generate test code
    if args.lang == "ts":
        test_content = generate_playwright_ts(
            routes=routes,
            base_url=args.base_url,
            check_contrast=not args.no_contrast
        )
        target_filename = "journey.spec.ts"
    else:
        test_content = generate_playwright_py(
            routes=routes,
            base_url=args.base_url,
            check_contrast=not args.no_contrast
        )
        target_filename = "test_journey.py"

    if args.dry_run:
        print("\n--- [DRY RUN: GENERATED TEST CODE] ---")
        print(test_content)
        return

    out_path = Path(args.out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    target_file = out_path / target_filename
    target_file.write_text(test_content, encoding="utf-8")

    print(f"\n[journey-craft] Successfully compiled E2E test suite:")
    print(f"  Target: {target_file.resolve()}")
    print(f"  Execution Command:")
    if args.lang == "ts":
        print(f"    npx playwright test {target_file.as_posix()}")
    else:
        print(f"    pytest {target_file.as_posix()}")

if __name__ == "__main__":
    main()
